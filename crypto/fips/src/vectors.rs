//! The known-answer vectors, as compiled-in constants (FIPS 140-3 IG 10.3.A: no "externally
//! provided input [test] text vectors, expected output results"). Each is copied from the source
//! named on it, which the crate docs' "Known-answer vectors" table also gives.
//!
//! The values were generated from the source files' hex by script, not typed, and each KAT is
//! also run against the algorithm crates in this crate's tests.

/// A hash KAT: `MD = HASH(Msg)`.
#[cfg(feature = "sha2")]
#[derive(Clone, Copy)]
pub(crate) struct HashKat<const MSG_LEN: usize, const MD_LEN: usize> {
    pub(crate) msg: [u8; MSG_LEN],
    pub(crate) md: [u8; MD_LEN],
}

#[cfg(feature = "aes")]
/// An AES-GCM KAT with a 96-bit IV and 128-bit plaintext, AAD and tag.
#[derive(Clone, Copy)]
pub(crate) struct GcmKat {
    pub(crate) key: [u8; 16],
    pub(crate) iv: [u8; 12],
    pub(crate) pt: [u8; 16],
    pub(crate) aad: [u8; 16],
    pub(crate) ct: [u8; 16],
    pub(crate) tag: [u8; 16],
}

/// An AES-CBC KAT over four blocks.
#[cfg(feature = "aes")]
#[derive(Clone, Copy)]
pub(crate) struct CbcKat {
    pub(crate) key: [u8; 16],
    pub(crate) iv: [u8; 16],
    pub(crate) ct: [u8; 64],
    pub(crate) pt: [u8; 64],
}

